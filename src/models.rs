//! `generated/entities.py` and `generated/events.py`: one dataclass per entity and per declared event payload,
//! so native trait code imports the same model names every shell generates (`<Trait><EVENT>Payload`).

use orbital_core_base::generate::GeneratedFile;
use orbital_core_base::ir::{
    render_default, render_type, OirEntity, OirField, OirModule, OirType, TargetLiteralRenderer,
    TargetTypeRenderer, TypeMappingClass,
};
use orbital_core_base::str_utils::{
    escape_python_string, sanitize_identifier, split_to_pascal_case, to_identifier_pascal,
};
use std::cell::RefCell;
use std::collections::{BTreeMap, BTreeSet};

const HEADER: &str = "# Generated by the Orbital compiler. Do not edit.\nfrom __future__ import annotations\n\nfrom dataclasses import dataclass, field\nfrom typing import Any, Literal\n\n";

const PY_KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield",
];

/// Names the generated modules import: an entity of the same name would shadow them.
const PY_RESERVED_TYPES: &[&str] = &["Any", "Literal", "dataclass", "field"];

fn py_identifier(name: &str) -> String {
    sanitize_identifier(name, PY_KEYWORDS)
}

fn entity_class(name: &str) -> String {
    let class = split_to_pascal_case(name);
    if PY_RESERVED_TYPES.contains(&class.as_str()) {
        format!("{class}Entity")
    } else {
        class
    }
}

fn symbol(name: &str) -> String {
    let valid = name
        .chars()
        .next()
        .is_some_and(|c| c.is_alphabetic() || c == '_')
        && name.chars().all(|c| c.is_alphanumeric() || c == '_');
    if valid {
        name.to_string()
    } else {
        to_identifier_pascal(name)
    }
}

struct PyTypes<'a> {
    context: String,
    hoisted: &'a RefCell<Vec<String>>,
    local: &'a BTreeSet<String>,
}

impl PyTypes<'_> {
    fn child(&self, context: String) -> PyTypes<'_> {
        PyTypes {
            context,
            hoisted: self.hoisted,
            local: self.local,
        }
    }
}

fn literal_union(values: &[String]) -> String {
    let members: Vec<String> = values
        .iter()
        .map(|v| format!("\"{}\"", escape_python_string(v)))
        .collect();
    format!("Literal[{}]", members.join(", "))
}

impl TargetTypeRenderer for PyTypes<'_> {
    type Out = String;

    fn string(&self, enum_values: Option<&[String]>) -> String {
        match enum_values {
            Some(values) if !values.is_empty() => literal_union(values),
            _ => "str".to_string(),
        }
    }
    fn number(&self) -> String {
        "float".to_string()
    }
    fn integer(&self) -> String {
        "int".to_string()
    }
    fn boolean(&self) -> String {
        "bool".to_string()
    }
    fn date(&self) -> String {
        "str".to_string()
    }
    fn json(&self) -> String {
        "Any".to_string()
    }
    fn enum_ty(&self, _name: &str, enum_values: Option<&[String]>) -> String {
        self.string(enum_values)
    }
    fn trait_ref(&self) -> String {
        "str".to_string()
    }
    fn sexpr(&self) -> String {
        "Any".to_string()
    }
    fn type_ref(&self, name: &str) -> String {
        orbital_core_base::type_compat::type_identifier(name)
    }
    fn row(&self, entity: &str) -> String {
        if self.local.contains(entity) {
            entity_class(entity)
        } else {
            "dict[str, Any]".to_string()
        }
    }
    fn array(&self, _inner_ty: &OirType, inner: String) -> String {
        format!("list[{inner}]")
    }
    fn map(&self, _key_ty: &OirType, key: String, _value_ty: &OirType, value: String) -> String {
        format!("dict[{key}, {value}]")
    }
    fn optional(&self, _inner_ty: &OirType, inner: String) -> String {
        format!("{inner} | None")
    }
    fn struct_ty(&self, fields: &[OirField], _additional: Option<&OirType>) -> String {
        let name = self.context.clone();
        let lines = field_lines(fields, &name, self);
        self.hoisted
            .borrow_mut()
            .push(dataclass(&name, None, &lines));
        name
    }
    fn union_ty(&self, variants: &[OirField]) -> String {
        if variants.is_empty() {
            return self.json();
        }
        let names: Vec<String> = variants
            .iter()
            .map(|v| {
                let name = format!("{}{}", self.context, split_to_pascal_case(&v.name));
                let lines = match &v.field_type {
                    OirType::Struct { fields, .. } => field_lines(fields, &name, self),
                    other => {
                        let child = self.child(format!("{name}Value"));
                        vec![format!("    value: {}", render_type(&child, other, None))]
                    }
                };
                self.hoisted
                    .borrow_mut()
                    .push(dataclass(&name, None, &lines));
                name
            })
            .collect();
        names.join(" | ")
    }

    fn classify_string(&self, _enum_values: Option<&[String]>) -> TypeMappingClass {
        TypeMappingClass::Faithful
    }
    fn classify_number(&self) -> TypeMappingClass {
        TypeMappingClass::Faithful
    }
    fn classify_integer(&self) -> TypeMappingClass {
        TypeMappingClass::Faithful
    }
    fn classify_boolean(&self) -> TypeMappingClass {
        TypeMappingClass::Faithful
    }
    fn classify_date(&self) -> TypeMappingClass {
        TypeMappingClass::Widening
    }
    fn classify_json(&self) -> TypeMappingClass {
        TypeMappingClass::Lossy
    }
    fn classify_enum_ty(&self, _name: &str, _enum_values: Option<&[String]>) -> TypeMappingClass {
        TypeMappingClass::Faithful
    }
    fn classify_trait_ref(&self) -> TypeMappingClass {
        TypeMappingClass::Widening
    }
    fn classify_sexpr(&self) -> TypeMappingClass {
        TypeMappingClass::Lossy
    }
    fn classify_row(&self, _entity: &str) -> TypeMappingClass {
        TypeMappingClass::Faithful
    }
    fn classify_type_ref(&self, _name: &str) -> TypeMappingClass {
        TypeMappingClass::Faithful
    }
    fn classify_array(&self, _inner_ty: &OirType, inner: TypeMappingClass) -> TypeMappingClass {
        inner
    }
    fn classify_map(
        &self,
        _key_ty: &OirType,
        key: TypeMappingClass,
        _value_ty: &OirType,
        value: TypeMappingClass,
    ) -> TypeMappingClass {
        key.meet(value)
    }
    fn classify_optional(&self, _inner_ty: &OirType, inner: TypeMappingClass) -> TypeMappingClass {
        inner
    }
    fn classify_struct_ty(
        &self,
        _fields: &[OirField],
        additional: Option<&OirType>,
    ) -> TypeMappingClass {
        if additional.is_some() {
            TypeMappingClass::Lossy
        } else {
            TypeMappingClass::Faithful
        }
    }
    fn classify_union_ty(&self, variants: &[OirField]) -> TypeMappingClass {
        if variants.is_empty() {
            self.classify_json()
        } else {
            TypeMappingClass::Faithful
        }
    }
}

struct PyLiteral;

impl TargetLiteralRenderer for PyLiteral {
    type Out = String;

    fn null(&self) -> String {
        "None".to_string()
    }
    fn bool(&self, b: bool) -> String {
        if b { "True" } else { "False" }.to_string()
    }
    fn integer(&self, i: i64) -> String {
        i.to_string()
    }
    fn number(&self, n: f64) -> String {
        let s = n.to_string();
        if s.contains('.') || s.contains('e') || s.contains('E') {
            s
        } else {
            format!("{s}.0")
        }
    }
    fn string(&self, s: &str) -> String {
        format!("\"{}\"", escape_python_string(s))
    }
    fn enum_member(&self, _enum_name: &str, member: &str) -> String {
        self.string(member)
    }
    fn array(&self, items: Vec<String>) -> String {
        format!("[{}]", items.join(", "))
    }
}

fn dataclass(name: &str, doc: Option<&str>, lines: &[String]) -> String {
    let mut out = format!("@dataclass(kw_only=True)\nclass {name}:\n");
    if let Some(doc) = doc {
        out.push_str(&format!("    \"\"\"{}\"\"\"\n", escape_python_string(doc)));
    }
    if lines.is_empty() && doc.is_none() {
        out.push_str("    pass\n");
    }
    for line in lines {
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// One `name: type = default` line per field. A non-required field is `T | None` carrying its declared default (or
/// `None`); a collection default is built per instance.
fn field_lines(fields: &[OirField], class: &str, types: &PyTypes<'_>) -> Vec<String> {
    fields
        .iter()
        .map(|f| field_line(f, class, types))
        .collect()
}

fn field_line(f: &OirField, class: &str, types: &PyTypes<'_>) -> String {
    let (ty, optional) = f.effective_type();
    let child = types.child(format!("{class}{}", split_to_pascal_case(&f.name)));
    let rendered = render_type(&child, ty, f.enum_values.as_deref());
    let annotation = if optional {
        format!("{rendered} | None")
    } else {
        rendered
    };
    let name = py_identifier(&f.name);
    let default = f.default.as_ref().map(|v| match render_default(&PyLiteral, v, ty, None) {
        Ok(rendered) => (rendered, None),
        Err(mismatch) => (Some("None".to_string()), Some(mismatch.marker())),
    });
    match default {
        Some((Some(value), marker)) => {
            let value = if value == "[]" {
                "field(default_factory=list)".to_string()
            } else if value.starts_with('[') {
                format!("field(default_factory=lambda: {value})")
            } else {
                value
            };
            let comment = marker.map(|m| format!("  # {m}")).unwrap_or_default();
            format!("    {name}: {annotation} = {value}{comment}")
        }
        _ if optional => format!("    {name}: {annotation} = None"),
        _ => format!("    {name}: {annotation}"),
    }
}

fn entity_source(entity: &OirEntity, types: &PyTypes<'_>) -> String {
    let class = entity_class(&entity.name);
    let hoisted = RefCell::new(Vec::new());
    let scoped = PyTypes {
        context: class.clone(),
        hoisted: &hoisted,
        local: types.local,
    };
    let mut lines = vec!["    id: str".to_string()];
    let rest: Vec<OirField> = entity
        .fields
        .iter()
        .filter(|f| f.name != "id")
        .cloned()
        .collect();
    lines.extend(field_lines(&rest, &class, &scoped));
    let mut out = String::new();
    for decl in hoisted.into_inner() {
        out.push_str(&decl);
        out.push_str("\n\n");
    }
    out.push_str(&dataclass(
        &class,
        Some(entity.description.as_deref().unwrap_or(&entity.name)),
        &lines,
    ));
    out
}

fn local_entities(module: &OirModule) -> BTreeSet<String> {
    module.entities.iter().map(|e| e.name.clone()).collect()
}

pub fn entities_file(module: &OirModule) -> GeneratedFile {
    let local = local_entities(module);
    let file_hoisted = RefCell::new(Vec::new());
    let types = PyTypes {
        context: String::new(),
        hoisted: &file_hoisted,
        local: &local,
    };
    for (name, ty) in &module.named_types {
        render_type(&types.child(orbital_core_base::type_compat::type_identifier(name)), ty, None);
    }
    let mut body = String::new();
    for decl in file_hoisted.take() {
        body.push_str(&decl);
        body.push_str("\n\n");
    }
    let mut names = Vec::new();
    for entity in module.distinct_entities() {
        names.push(entity_class(&entity.name));
        body.push_str(&entity_source(&entity, &types));
        body.push_str("\n\n");
    }
    let all: Vec<String> = names.iter().map(|n| format!("\"{n}\"")).collect();
    GeneratedFile::new(
        "entities.py",
        format!(
            "{HEADER}__all__ = [{}]\n\n\n{}",
            all.join(", "),
            body.trim_end().to_string() + "\n"
        ),
    )
}

/// The payload type of every event a trait declares or emits with a payload, keyed by the TypeScript shell's
/// `<Trait><EVENT>Payload` name; the payload-typed entry wins when a key appears twice.
fn payloads(module: &OirModule) -> BTreeMap<String, Vec<OirField>> {
    let mut out = BTreeMap::new();
    for t in &module.traits {
        for event in &t.events {
            let Some(schema) = event.payload_schema.as_ref().filter(|s| !s.is_empty()) else {
                continue;
            };
            let mut fields: Vec<OirField> = schema
                .iter()
                .map(|(k, v)| OirField::new(k.clone(), v.clone()))
                .collect();
            fields.sort_by(|a, b| a.name.cmp(&b.name));
            out.insert(format!("{}{}Payload", symbol(&t.name), symbol(&event.key)), fields);
        }
    }
    out
}

pub fn events_file(module: &OirModule) -> GeneratedFile {
    let local = local_entities(module);
    let hoisted = RefCell::new(Vec::new());
    let mut body = String::new();
    for (name, fields) in payloads(module) {
        let types = PyTypes {
            context: name.clone(),
            hoisted: &hoisted,
            local: &local,
        };
        let lines = field_lines(&fields, &name, &types);
        for decl in hoisted.take() {
            body.push_str(&decl);
            body.push_str("\n\n");
        }
        body.push_str(&dataclass(&name, None, &lines));
        body.push_str("\n\n");
    }
    GeneratedFile::new(
        "events.py",
        format!(
            "{HEADER}from .entities import *  # noqa: F401,F403\n\n\n{}",
            body.trim_end().to_string() + "\n"
        ),
    )
}

pub fn package_file() -> GeneratedFile {
    GeneratedFile::new("__init__.py", String::new())
}

#[cfg(test)]
mod tests {
    use super::*;
    use orbital_core_base::ir::{OirEvent, OirTrait, OirValue};

    fn module(with_trait: bool) -> OirModule {
        let mut m = OirModule::new("app", "1.0.0");
        let mut doc = OirEntity::new("Doc");
        doc.fields.push(OirField::new("id", OirType::String));
        doc.fields.push({
            let mut f = OirField::new("chunks", OirType::Array { inner: Box::new(OirType::String) });
            f.required = false;
            f.default = Some(OirValue::Array(vec![]));
            f
        });
        doc.fields.push({
            let mut f = OirField::new("status", OirType::String);
            f.enum_values = Some(vec!["open".into(), "closed".into()]);
            f
        });
        doc.fields.push(OirField::optional("note", OirType::String));
        m.entities.push(doc);
        if with_trait {
            let mut t = OirTrait::new("Chunk");
            let mut listened = OirEvent::new("CHUNK");
            let mut schema = orbital_core_base::ir::OirTypeMap::new();
            schema.insert("text".into(), OirType::String);
            schema.insert("size".into(), OirType::Number);
            listened.payload_schema = Some(schema);
            let mut emitted = OirEvent::new("CHUNKED");
            let mut schema = orbital_core_base::ir::OirTypeMap::new();
            schema.insert("count".into(), OirType::Integer);
            emitted.payload_schema = Some(schema);
            t.events = vec![listened, emitted, OirEvent::new("RESET")];
            m.traits.push(t);
        }
        m
    }

    #[test]
    fn entities_render_required_defaulted_enum_and_optional_fields() {
        let file = entities_file(&module(false));
        assert_eq!(file.path, "entities.py");
        let expected = "@dataclass(kw_only=True)\nclass Doc:\n    \"\"\"Doc\"\"\"\n    id: str\n    chunks: list[str] | None = field(default_factory=list)\n    status: Literal[\"open\", \"closed\"]\n    note: str | None = None\n";
        assert!(file.content.contains(expected), "{}", file.content);
        assert!(file.content.contains("__all__ = [\"Doc\"]"));
    }

    #[test]
    fn control_a_required_field_without_default_has_no_none() {
        let file = entities_file(&module(false));
        assert!(!file.content.contains("status: Literal[\"open\", \"closed\"] | None"));
        assert!(!file.content.contains("id: str ="));
    }

    fn holder_module(alias: &str) -> OirModule {
        let mut m = OirModule::new("app", "1.0.0");
        m.named_types.insert(
            alias.to_string(),
            OirType::Struct { additional: None, fields: vec![OirField::new("id", OirType::String)].into() },
        );
        let mut holder = OirEntity::new("Holder");
        holder.fields.push(OirField::new("claim", OirType::TypeRef { name: alias.to_string() }));
        m.entities.push(holder);
        m
    }

    #[test]
    fn a_behavior_qualified_alias_is_one_identifier_at_declaration_and_reference() {
        let content = entities_file(&holder_module("std-foo::Bar")).content;
        assert!(content.contains("class StdFooBar:\n    id: str"), "{content}");
        assert!(content.contains("    claim: StdFooBar\n"), "{content}");
        assert!(!content.contains("::"), "{content}");
    }

    #[test]
    fn control_an_unqualified_alias_is_spelled_as_written() {
        let content = entities_file(&holder_module("Bar")).content;
        assert!(content.contains("class Bar:\n    id: str"), "{content}");
        assert!(content.contains("    claim: Bar\n"), "{content}");
        assert!(!content.contains("StdFoo"), "{content}");
    }

    #[test]
    fn events_render_one_payload_per_declared_payload_with_sorted_fields() {
        let file = events_file(&module(true));
        let chunk = "@dataclass(kw_only=True)\nclass ChunkCHUNKPayload:\n    size: float\n    text: str\n";
        let chunked = "@dataclass(kw_only=True)\nclass ChunkCHUNKEDPayload:\n    count: int\n";
        assert!(file.content.contains(chunk), "{}", file.content);
        assert!(file.content.contains(chunked), "{}", file.content);
        assert!(file.content.contains("from .entities import *"));
    }

    #[test]
    fn control_a_void_event_and_a_traitless_module_declare_no_payload() {
        assert!(!events_file(&module(true)).content.contains("ChunkRESETPayload"));
        assert!(!events_file(&module(false)).content.contains("class "));
    }
}
