/// Generate setup code to satisfy guard conditions
/// Returns (setup_code, description) if guard needs setup, None otherwise
///
/// This uses the entity definition from the OIR to determine which fields
/// need mock values. Fields that already have defaults in the entity
/// definition are NOT overwritten, preventing test breakage from
/// incompatible mock values.
fn generate_guard_setup(
    transition: &OirTransition,
    trait_def: &OirTrait,
    module: &OirModule,
    module_name: &str,
) -> Option<(String, String)> {
    let mut entity_setup = Vec::new();

    // Get the linked entity to check field defaults
    let linked_entity = get_linked_entity(trait_def, module);

    // Analyze guard expression for required entity state
    if let Some(guard) = transition.guard.as_ref() {
        entity_setup.extend(analyze_guard_for_setup(guard, Some(trait_def)));
    }

    // Analyze effects for arrays that need initialization (append operations)
    // and entity fields that need mock values
    for effect in &transition.effects {
        if let Some(field) = extract_append_target_field(effect) {
            // Initialize array if not already set by guard setup
            if !entity_setup.iter().any(|(k, _)| k == &field) {
                entity_setup.push((field, "[]".to_string()));
            }
        }

        // Extract entity fields accessed in effects
        let effect_fields = extract_effect_entity_fields(effect);
        for field in effect_fields {
            // Skip if already set up
            if entity_setup.iter().any(|(k, _)| k == &field) {
                continue;
            }

            // Decision tree for whether to mock a field:
            //
            // 1. Field has default in entity? → DON'T mock (already initialized)
            // 2. Field is SET by this trait's transitions? → DON'T mock (prior transition sets it)
            // 3. Otherwise → MOCK (it's an external dependency that needs a value)
            //
            // This correctly handles:
            // - inputSize (default: 16) → don't mock
            // - architecture (set by INIT effect) → don't mock
            // - model (external reference, not set by trait) → mock
            // - validationData (external reference) → mock

            if let Some(entity) = linked_entity {
                if field_has_default(&field, entity) {
                    // Field has a default - don't override it
                    continue;
                }
            }

            if field_set_by_trait(&field, trait_def) {
                // Field is set by another transition in this trait - don't mock
                continue;
            }

            // Field needs mock value - it's an external dependency
            entity_setup.push((field.clone(), get_mock_value_for_field(&field)));
        }
    }

    if entity_setup.is_empty() {
        return None;
    }

    let mut code = String::new();
    code.push_str("        # Setup entity state to satisfy guard condition\n");

    // Build the setup dict
    let setup_fields: Vec<String> = entity_setup
        .iter()
        .map(|(k, v)| format!("\"{}\": {}", k, v))
        .collect();
    let setup_dict = format!("{{{}}}", setup_fields.join(", "));

    code.push_str(&format!(
        "        await client.post(\"/api/{}/set-entity\", json={})\n",
        module_name, setup_dict
    ));

    let description = format!(
        "Setup for guard: {:?}",
        entity_setup
            .iter()
            .map(|(k, _)| k.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    );
    Some((code, description))
}

/// Extract all entity fields accessed in an effect expression
fn extract_effect_entity_fields(expr: &OirExpr) -> Vec<String> {
    let mut fields = Vec::new();
    collect_entity_fields(expr, &mut fields);
    fields
}

/// Recursively collect entity field names from an expression
fn collect_entity_fields(expr: &OirExpr, fields: &mut Vec<String>) {
    match expr {
        OirExpr::Binding { binding } => {
            if matches!(binding.root, OirBindingRoot::Entity) && !binding.path.is_empty() {
                if let Some(field) = binding.path.last() {
                    if !fields.contains(field) {
                        fields.push(field.clone());
                    }
                }
            }
        }
        OirExpr::Call { args, .. } => {
            for arg in args {
                collect_entity_fields(arg, fields);
            }
        }
        OirExpr::Object { fields: obj_fields } => {
            for (_, v) in obj_fields {
                collect_entity_fields(v, fields);
            }
        }
        OirExpr::Array { items } => {
            for item in items {
                collect_entity_fields(item, fields);
            }
        }
        OirExpr::BinaryOp { left, right, .. } => {
            collect_entity_fields(left, fields);
            collect_entity_fields(right, fields);
        }
        OirExpr::Effect { effect } => {
            match effect.as_ref() {
                OirEffect::Set { target, value, .. } => {
                    // Collect fields from value but not from target (target is what we're setting)
                    collect_entity_fields(value, fields);
                    // Also check if we read from target's path before the last element
                    if matches!(target.root, OirBindingRoot::Entity) && target.path.len() > 1 {
                        // Parent path elements might need to exist
                        for path_elem in &target.path[..target.path.len() - 1] {
                            if !fields.contains(path_elem) {
                                fields.push(path_elem.clone());
                            }
                        }
                    }
                }
                OirEffect::Emit { payload, .. } => {
                    if let Some(p) = payload {
                        collect_entity_fields(p, fields);
                    }
                }
                _ => {}
            }
        }
        OirExpr::Conditional {
            condition,
            then_branch,
            else_branch,
        } => {
            collect_entity_fields(condition, fields);
            collect_entity_fields(then_branch, fields);
            collect_entity_fields(else_branch, fields);
        }
        OirExpr::Map { source, body, .. }
        | OirExpr::Filter {
            source,
            predicate: body,
            ..
        } => {
            collect_entity_fields(source, fields);
            collect_entity_fields(body, fields);
        }
        OirExpr::Reduce {
            source,
            initial,
            body,
            ..
        } => {
            collect_entity_fields(source, fields);
            collect_entity_fields(initial, fields);
            collect_entity_fields(body, fields);
        }
        OirExpr::UnaryOp { operand, .. } => {
            collect_entity_fields(operand, fields);
        }
        _ => {}
    }
}

/// Extract the target field from an append effect
/// Returns field name if effect is appending to @entity.field
fn extract_append_target_field(effect: &OirExpr) -> Option<String> {
    match effect {
        // Handle OirExpr::Effect variant
        OirExpr::Effect {
            effect: inner_effect,
        } => {
            if let OirEffect::Set { target, value, .. } = inner_effect.as_ref() {
                // Check if value is an append call
                if let OirExpr::Call { function, args } = value {
                    if function == "append" && !args.is_empty() {
                        // Get the target field from the set target
                        return target.path.last().cloned();
                    }
                }
            }
        }
        // Handle OirExpr::Call variant (for "set" calls with append)
        OirExpr::Call { function, args } => {
            if function == "set" && args.len() >= 2 {
                if let OirExpr::Call {
                    function: inner_fn, ..
                } = &args[1]
                {
                    if inner_fn == "append" {
                        return extract_entity_field(&args[0]);
                    }
                }
            }
        }
        _ => {}
    }
    None
}

/// Analyze a guard expression and return entity fields that need to be set
/// If trait_def is provided, analyzes effects to determine array item structures
fn analyze_guard_for_setup(expr: &OirExpr, trait_def: Option<&OirTrait>) -> Vec<(String, String)> {
    let mut setup = Vec::new();

    match expr {
        OirExpr::BinaryOp { op, left, right } => {
            match op {
                // Handle comparisons like entity["status"] == "ready"
                OirBinaryOp::Eq => {
                    if let (Some(field), Some(value)) =
                        (extract_entity_field(left), extract_literal_value(right))
                    {
                        setup.push((field, value));
                    } else if let (Some(field), Some(value)) =
                        (extract_entity_field(right), extract_literal_value(left))
                    {
                        setup.push((field, value));
                    }
                }
                // Handle len/count(entity["buffer"]) > N or entity["field1"] >= entity["field2"]
                OirBinaryOp::Gt | OirBinaryOp::Ge => {
                    if let Some((field, min_len)) = extract_length_check(left, right) {
                        // Try to infer item structure from trait effects
                        let item_template = trait_def
                            .and_then(|t| infer_array_item_structure(t, &field))
                            .unwrap_or_else(|| "{\"item\": 0}".to_string());

                        // Generate a list with enough items using the inferred template
                        let items: Vec<String> = (0..=min_len)
                            .map(|i| {
                                // Replace placeholder values in template with index-based values
                                item_template
                                    .replace("__INDEX__", &i.to_string())
                                    .replace("__FLOAT__", &format!("{:.1}", i as f64 * 0.1))
                                    .replace("__LABEL__", &format!("label_{}", i))
                            })
                            .collect();
                        setup.push((field, format!("[{}]", items.join(", "))));
                    } else if let (Some(field1), Some(field2)) =
                        (extract_entity_field(left), extract_entity_field(right))
                    {
                        // Handle field1 >= field2 by setting both to same value
                        setup.push((field1, "10".to_string()));
                        setup.push((field2, "10".to_string()));
                    }
                }
                // Handle entity["currentEpoch"] < entity["epochs"]
                OirBinaryOp::Lt | OirBinaryOp::Le => {
                    if let (Some(field1), Some(field2)) =
                        (extract_entity_field(left), extract_entity_field(right))
                    {
                        // Set field1 to 0 and field2 to a positive number
                        setup.push((field1, "0".to_string()));
                        setup.push((field2, "10".to_string()));
                    }
                }
                // Handle AND conditions
                OirBinaryOp::And => {
                    setup.extend(analyze_guard_for_setup(left, trait_def));
                    setup.extend(analyze_guard_for_setup(right, trait_def));
                }
                _ => {}
            }
        }
        _ => {}
    }

    setup
}

/// Infer the structure of array items by analyzing transition effects
/// Looks for patterns like: ["set", "@entity.field", ["append", "@entity.field", { structure }]]
fn infer_array_item_structure(trait_def: &OirTrait, field_name: &str) -> Option<String> {
    for transition in &trait_def.transitions {
        for effect in &transition.effects {
            if let Some(structure) = extract_append_item_structure(effect, field_name) {
                return Some(structure);
            }
        }
    }
    None
}

/// Extract the item structure from an append effect
/// Pattern: ["set", "@entity.field", ["append", "@entity.field", { item_structure }]]
fn extract_append_item_structure(effect: &OirExpr, target_field: &str) -> Option<String> {
    // Effects can be represented in two ways:
    // 1. OirExpr::Effect { effect: OirEffect::Set { target, value } }
    // 2. OirExpr::Call { function: "set", args: [target, value] }

    match effect {
        // Handle OirExpr::Effect variant (the OIR representation)
        OirExpr::Effect {
            effect: inner_effect,
        } => {
            if let OirEffect::Set { target, value, .. } = inner_effect.as_ref() {
                let field = target.path.last().map(|s| s.as_str()).unwrap_or("");
                if field == target_field {
                    // Check if value is an append call
                    if let OirExpr::Call { function, args } = value {
                        if function == "append" && args.len() >= 2 {
                            let item = args.last()?;
                            return Some(expr_to_test_template(item));
                        }
                    }
                }
            }
        }
        // Handle OirExpr::Call variant (legacy/alternative representation)
        OirExpr::Call { function, args } => {
            if function == "set" && args.len() >= 2 {
                if let Some(field) = extract_entity_field(&args[0]) {
                    if field == target_field {
                        if let OirExpr::Call {
                            function: inner_fn,
                            args: inner_args,
                        } = &args[1]
                        {
                            if inner_fn == "append" && inner_args.len() >= 2 {
                                let item = inner_args.last()?;
                                return Some(expr_to_test_template(item));
                            }
                        }
                    }
                }
            }
        }
        _ => {}
    }
    None
}

/// Convert an OirExpr to a test template string
/// Replaces @payload bindings with placeholder values
fn expr_to_test_template(expr: &OirExpr) -> String {
    match expr {
        OirExpr::Object { fields } => {
            let field_strs: Vec<String> = fields
                .iter()
                .map(|(k, v)| {
                    let value = expr_to_test_value(v);
                    format!("\"{}\": {}", k, value)
                })
                .collect();
            format!("{{{}}}", field_strs.join(", "))
        }
        OirExpr::Array { items } => {
            let elem_strs: Vec<String> = items.iter().map(expr_to_test_value).collect();
            format!("[{}]", elem_strs.join(", "))
        }
        _ => expr_to_test_value(expr),
    }
}

/// Convert an OirExpr to a test value string
fn expr_to_test_value(expr: &OirExpr) -> String {
    match expr {
        OirExpr::String { value } => format!("\"{}\"", value),
        OirExpr::Number { value } => {
            if value.fract() == 0.0 {
                format!("{}", *value as i64)
            } else {
                value.to_string()
            }
        }
        OirExpr::Bool { value } => if *value { "true" } else { "false" }.to_string(),
        OirExpr::Binding { binding } => {
            // Replace @payload bindings with test placeholders
            match &binding.root {
                OirBindingRoot::Payload => {
                    // Use field name to generate appropriate test value
                    let field = binding.path.last().map(|s| s.as_str()).unwrap_or("value");
                    if field.contains("data") || field.contains("input") {
                        "[__FLOAT__]".to_string()
                    } else if field.contains("label") || field.contains("target") {
                        "\"__LABEL__\"".to_string()
                    } else {
                        "__INDEX__".to_string()
                    }
                }
                _ => "null".to_string(),
            }
        }
        OirExpr::Object { fields } => {
            let field_strs: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("\"{}\": {}", k, expr_to_test_value(v)))
                .collect();
            format!("{{{}}}", field_strs.join(", "))
        }
        OirExpr::Array { items } => {
            let elem_strs: Vec<String> = items.iter().map(expr_to_test_value).collect();
            format!("[{}]", elem_strs.join(", "))
        }
        _ => "null".to_string(),
    }
}

/// Extract entity field name from an expression like entity["fieldName"]
fn extract_entity_field(expr: &OirExpr) -> Option<String> {
    match expr {
        OirExpr::Binding { binding } => {
            if matches!(binding.root, OirBindingRoot::Entity) && !binding.path.is_empty() {
                Some(binding.path.last()?.clone())
            } else {
                None
            }
        }
        // Handle len/count(entity["field"])
        OirExpr::Call { function, args }
            if function == "len" || function == "array/length" || function == "count" =>
        {
            if let Some(arg) = args.first() {
                extract_entity_field(arg)
            } else {
                None
            }
        }
        _ => None,
    }
}

/// Extract literal value from expression
fn extract_literal_value(expr: &OirExpr) -> Option<String> {
    match expr {
        OirExpr::String { value } => Some(format!("\"{}\"", value)),
        OirExpr::Number { value } => {
            if value.fract() == 0.0 {
                Some(format!("{}", *value as i64))
            } else {
                Some(value.to_string())
            }
        }
        OirExpr::Bool { value } => Some(if *value { "True" } else { "False" }.to_string()),
        _ => None,
    }
}

/// Extract length check pattern: len/count(entity["field"]) > N
fn extract_length_check(left: &OirExpr, right: &OirExpr) -> Option<(String, usize)> {
    // Check if left is len/count(entity["field"]) and right is a number
    if let OirExpr::Call { function, args } = left {
        if (function == "len" || function == "array/length" || function == "count")
            && !args.is_empty()
        {
            if let Some(field) = extract_entity_field(&args[0]) {
                if let OirExpr::Number { value } = right {
                    return Some((field, *value as usize));
                }
            }
        }
    }
    None
}

