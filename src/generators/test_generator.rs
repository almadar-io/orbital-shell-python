/// Represents a step in the path with all necessary info for guard setup
#[derive(Clone)]
struct PathStep<'a> {
    event: String,
    payload: String,
    transition: &'a OirTransition,
}

/// Find a path of events to reach target state from start state
#[allow(dead_code)]
fn find_path_to_state(trait_def: &OirTrait, start: &str, target: &str) -> Vec<(String, String)> {
    find_path_with_transitions(trait_def, start, target)
        .into_iter()
        .map(|step| (step.event, step.payload))
        .collect()
}

/// Find a path of transitions to reach target state, including guard info
fn find_path_with_transitions<'a>(
    trait_def: &'a OirTrait,
    start: &str,
    target: &str,
) -> Vec<PathStep<'a>> {
    if start == target {
        return vec![];
    }

    // BFS to find shortest path
    use std::collections::{HashSet, VecDeque};

    let mut visited: HashSet<String> = HashSet::new();
    let mut queue: VecDeque<(String, Vec<PathStep<'a>>)> = VecDeque::new();

    // Build adjacency map with transition references
    let mut adj: std::collections::BTreeMap<String, Vec<&'a OirTransition>> = std::collections::BTreeMap::new();
    for t in &trait_def.transitions {
        let from_states = match &t.from {
            OirTransitionFrom::Single(s) => vec![s.clone()],
            OirTransitionFrom::Multiple(ss) => ss.clone(),
            OirTransitionFrom::Any => continue, // Skip * transitions in pathfinding
        };
        for from in from_states {
            adj.entry(from).or_default().push(t);
        }
    }

    queue.push_back((start.to_string(), vec![]));
    visited.insert(start.to_string());

    while let Some((current, path)) = queue.pop_front() {
        if current == target {
            return path;
        }

        if let Some(transitions) = adj.get(&current) {
            for t in transitions {
                if !visited.contains(&t.to) {
                    visited.insert(t.to.clone());
                    let mut new_path = path.clone();
                    let payload = get_event_payload(trait_def, &t.event);
                    new_path.push(PathStep {
                        event: t.event.clone(),
                        payload,
                        transition: t,
                    });
                    queue.push_back((t.to.clone(), new_path));
                }
            }
        }
    }

    vec![] // No path found
}

/// Get sample payload for an event
fn get_event_payload(trait_def: &OirTrait, event_name: &str) -> String {
    if let Some(event) = trait_def.events.iter().find(|e| e.key == event_name) {
        if let Some(ref schema) = event.payload_schema {
            if !schema.is_empty() {
                let mut payload_parts = vec![];
                for (field_name, _) in schema {
                    let mock_val = get_mock_value_for_field(field_name);
                    payload_parts.push(format!("\"{}\": {}", field_name, mock_val));
                }
                return format!("{{{}}}", payload_parts.join(", "));
            }
        }
    }
    "{}".to_string()
}

/// Build a journey that visits all states
fn build_journey(trait_def: &OirTrait) -> Vec<(String, String, String)> {
    let mut journey = vec![];
    let mut visited: std::collections::HashSet<String> = std::collections::HashSet::new();

    // Get initial state
    let initial = trait_def
        .states
        .iter()
        .find(|s| s.is_initial)
        .map(|s| s.name.clone())
        .unwrap_or_else(|| {
            trait_def
                .states
                .first()
                .map(|s| s.name.clone())
                .unwrap_or_default()
        });

    if initial.is_empty() {
        return journey;
    }

    let mut current = initial.clone();
    visited.insert(current.clone());

    // Try to visit all states
    let max_iterations = trait_def.states.len() * 2;
    let mut iterations = 0;

    while visited.len() < trait_def.states.len() && iterations < max_iterations {
        iterations += 1;

        // Find a transition from current state to an unvisited state
        let mut found = false;
        for transition in &trait_def.transitions {
            let can_transition = match &transition.from {
                OirTransitionFrom::Single(s) => s == &current,
                OirTransitionFrom::Multiple(ss) => ss.contains(&current),
                OirTransitionFrom::Any => true,
            };

            if can_transition && !visited.contains(&transition.to) {
                let payload = get_event_payload(trait_def, &transition.event);
                journey.push((transition.event.clone(), payload, transition.to.clone()));
                current = transition.to.clone();
                visited.insert(current.clone());
                found = true;
                break;
            }
        }

        // If no unvisited state, try any valid transition
        if !found {
            for transition in &trait_def.transitions {
                let can_transition = match &transition.from {
                    OirTransitionFrom::Single(s) => s == &current,
                    OirTransitionFrom::Multiple(ss) => ss.contains(&current),
                    OirTransitionFrom::Any => true,
                };

                if can_transition {
                    let payload = get_event_payload(trait_def, &transition.event);
                    journey.push((transition.event.clone(), payload, transition.to.clone()));
                    current = transition.to.clone();
                    break;
                }
            }
        }
    }

    journey
}

/// Get the linked entity for a trait from the module
fn get_linked_entity<'a>(trait_def: &OirTrait, module: &'a OirModule) -> Option<&'a OirEntity> {
    trait_def
        .linked_entity
        .as_ref()
        .and_then(|name| module.entities.iter().find(|e| &e.name == name))
}

/// Check if a field has a default value in the entity definition
/// Returns true if the field has a default (either field-level or entity-level)
fn field_has_default(field_name: &str, entity: &OirEntity) -> bool {
    // Check field-level default
    if let Some(field) = entity.fields.iter().find(|f| f.name == field_name) {
        if field.default.is_some() {
            return true;
        }
    }

    // Check entity-level defaults
    if let Some(defaults) = &entity.defaults {
        if defaults.contains_key(field_name) {
            return true;
        }
    }

    false
}

/// Check if a field is SET by any transition in the trait
/// This detects fields like "architecture" that are created by INIT
fn field_set_by_trait(field_name: &str, trait_def: &OirTrait) -> bool {
    for transition in &trait_def.transitions {
        for effect in &transition.effects {
            if is_field_set_target(field_name, effect) {
                return true;
            }
        }
    }
    false
}

/// Check if an expression sets the given field
fn is_field_set_target(field_name: &str, expr: &OirExpr) -> bool {
    match expr {
        OirExpr::Effect { effect } => {
            if let OirEffect::Set { target, .. } = effect.as_ref() {
                if matches!(target.root, OirBindingRoot::Entity) {
                    if let Some(last) = target.path.last() {
                        return last == field_name;
                    }
                }
            }
        }
        OirExpr::Call { function, args } if function == "set" && args.len() >= 2 => {
            if let Some(target_field) = extract_entity_field(&args[0]) {
                return target_field == field_name;
            }
        }
        _ => {}
    }
    false
}

