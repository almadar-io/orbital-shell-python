//! Trait Generator for Python
//!
//! Generates state machine classes from OIR traits.

use crate::codegen::{compile_binding_to_py, compile_expr_to_py, CodegenContext};
use orbital_core::ir::{
    is_substrate_operator, OirEffect, OirEmitConfig, OirExpr, OirModule, OirPersistOp, OirTrait,
    OirTransition, OirTransitionFrom,
};
use orbital_core::str_utils::to_snake_case;

/// Generate trait state machine classes
pub fn generate_traits(module: &OirModule) -> Vec<(String, String)> {
    module
        .traits
        .iter()
        .map(|trait_def| {
            let filename = format!("{}.py", to_snake_case(&trait_def.name));
            let content = generate_trait(trait_def);
            (filename, content)
        })
        .collect()
}

/// Generate a single trait class
fn generate_trait(trait_def: &OirTrait) -> String {
    let mut code = String::new();

    // File header
    code.push_str(&format!(
        "\"\"\"
{} Trait

State machine implementation for {}.
Auto-generated by Orbital Compiler.
\"\"\"\n\n",
        trait_def.name, trait_def.name
    ));

    // Imports
    code.push_str("from __future__ import annotations\n");
    code.push_str("from typing import List, Dict, Optional, Any, TYPE_CHECKING\n");
    code.push_str("from enum import Enum\n");
    code.push_str("from dataclasses import dataclass\n");
    code.push_str("import torch\n");
    code.push_str("import torch.nn as nn\n");
    code.push_str("import torch.nn.functional as F\n");
    code.push_str("import copy\n");
    code.push_str("import random\n");
    code.push_str("import functools\n");
    code.push_str("import json\n");
    code.push_str("import math\n\n");

    code.push_str("if TYPE_CHECKING:\n");
    code.push_str("    from ...core.event_bus import EventBus\n\n");
    code.push_str("from ...core.event_bus import SourceTaggedBus\n\n");

    // Import helper functions
    code.push_str("from ..nn_helpers import build_network, set_weights, build_layer\n");
    code.push_str("from ..tensor_helpers import clamp_per_dim, out_of_range_dims\n");
    code.push_str("from ..train_helpers import train_loop, train_step, validate, check_constraints, clip_weights, compute_returns, compute_advantages, check_weight_magnitude, check_forbidden_outputs\n");
    code.push_str(
        "from ..effect_helpers import notify, render_ui, navigate, spawn, despawn, now\n",
    );
    code.push_str("from ..ml_effect_helpers import ml_forward, ml_train, ml_evaluate, checkpoint_save, checkpoint_load\n");
    code.push_str("from ..std_helpers import array_nearest, object_get, object_merge, object_set, array_filter, array_flatten, array_max, array_min, array_group, grid_manhattan, grid_chebyshev, grid_in_bounds, time_parse, time_format, time_unit_ms, time_year, time_month, time_day, time_hour, time_minute, time_second, time_weekday\n");
    code.push_str("from ..prob_helpers import prob_poisson, prob_expected_value, prob_variance, prob_percentile, prob_credible_interval, prob_histogram\n");
    code.push_str("from ..contract_helpers import contract_validate_input, contract_validate_output, contract_clamp_output, contract_violations, contract_entity_to_tensor, contract_tensor_to_payload\n\n");

    // Generate state enum
    code.push_str(&generate_state_enum(trait_def));
    code.push_str("\n\n");

    // Generate trait class
    code.push_str(&generate_trait_class(trait_def));

    code
}

/// Generate state enum
fn generate_state_enum(trait_def: &OirTrait) -> String {
    let mut code = String::new();

    let enum_name = format!("{}State", trait_def.name);
    code.push_str(&format!("class {}(Enum):\n", enum_name));
    code.push_str(&format!(
        "    \"\"\"States for {} trait.\"\"\"\n",
        trait_def.name
    ));

    if !trait_def.states.is_empty() {
        for state in &trait_def.states {
            let state_upper = state.name.to_uppercase().replace('-', "_");
            code.push_str(&format!("    {} = \"{}\"\n", state_upper, state.name));
        }
    } else {
        code.push_str("    IDLE = \"idle\"\n");
    }

    code
}

/// Generate trait class with state machine
fn generate_trait_class(trait_def: &OirTrait) -> String {
    let mut code = String::new();

    let class_name = &trait_def.name;
    let state_enum = format!("{}State", trait_def.name);

    // Class definition
    code.push_str(&format!("class {}:\n", class_name));
    code.push_str(&format!(
        "    \"\"\"
    {} trait implementation.

    {}
    \"\"\"\n\n",
        class_name,
        trait_def.description.as_deref().unwrap_or("")
    ));

    // Constructor
    code.push_str("    def __init__(self):\n");

    // Initial state
    let initial_state = trait_def
        .states
        .iter()
        .find(|s| s.is_initial)
        .map(|s| s.name.to_uppercase().replace('-', "_"))
        .unwrap_or_else(|| "IDLE".to_string());

    code.push_str(&format!(
        "        self._state = {}.{}\n",
        state_enum, initial_state
    ));
    code.push_str("        self._event_bus: Optional['EventBus'] = None\n");
    // Repository + service stubs — injected at construction or replaced via set_* methods
    code.push_str("        self._repository = None  # Set via set_repository()\n");
    code.push_str("        self._call_service = None  # Set via set_service_client()\n");
    code.push_str("        self._llm_generate = None  # Set via set_llm_client()\n");
    code.push_str("        self._invoke_tool = None  # Set via set_tool_registry()\n");

    // Cache for PyTorch modules (indexed by entity_id)
    code.push_str("        # Cache for PyTorch modules (indexed by entity_id)\n");
    code.push_str("        self._architectures: Dict[str, nn.Module] = {}\n\n");

    // Cross-trait listens metadata (consumed by setup_event_listeners at startup)
    code.push_str(&generate_listens_metadata(trait_def));

    // State property
    code.push_str("    @property\n");
    code.push_str(&format!("    def state(self) -> {}:\n", state_enum));
    code.push_str("        \"\"\"Current state of the trait.\"\"\"\n");
    code.push_str("        return self._state\n\n");

    // Set event bus
    code.push_str("    def set_event_bus(self, event_bus: 'EventBus'):\n");
    code.push_str("        \"\"\"Set the event bus for emitting events.\n\n");
    code.push_str("        Every emit is auto-tagged with this trait's class name so\n");
    code.push_str("        cross-trait listeners can filter by source (mirrors the JS\n");
    code.push_str("        runtime's source-scoped listens).\n");
    code.push_str("        \"\"\"\n");
    code.push_str("        self._event_bus = SourceTaggedBus(event_bus, self.__class__.__name__, self) if event_bus else None\n\n");

    // Inject repository (persist effects)
    code.push_str("    def set_repository(self, repository):\n");
    code.push_str("        self._repository = repository\n\n");

    // Inject service client (call-service effects)
    code.push_str("    def set_service_client(self, call_service):\n");
    code.push_str("        self._call_service = call_service\n\n");

    // Inject LLM client (agent/generate)
    code.push_str("    def set_llm_client(self, llm_generate):\n");
    code.push_str("        self._llm_generate = llm_generate\n\n");

    // Inject tool registry (agent/invoke)
    code.push_str("    def set_tool_registry(self, invoke_tool):\n");
    code.push_str("        self._invoke_tool = invoke_tool\n\n");

    // Architecture cache helpers
    code.push_str("    def _get_architecture(self, entity_id: str) -> Optional[nn.Module]:\n");
    code.push_str("        \"\"\"Get cached architecture for entity.\"\"\"\n");
    code.push_str("        return self._architectures.get(entity_id)\n\n");

    code.push_str(
        "    def _set_architecture(self, entity_id: str, arch: nn.Module) -> nn.Module:\n",
    );
    code.push_str("        \"\"\"Cache architecture for entity and return it.\"\"\"\n");
    code.push_str("        self._architectures[entity_id] = arch\n");
    code.push_str("        return arch\n\n");

    // Dispatch method — drains the self-callback escalation chain.
    // A headless server has no client to relay emitted events back, so dispatch
    // re-enters any emitted event the SAME trait handles (service-callbacks:
    // ASK → fires embed → emits EMBEDDED → handle_EMBEDDED → ... ). External
    // emits (no handler on self) are left for the bus + cross-trait wiring.
    // Depth-capped (circuit breaker, mirroring the JS bus) to prevent runaway.
    code.push_str("    async def dispatch(self, event: str, entity: Any, payload: Dict[str, Any]) -> tuple:\n");
    code.push_str("        \"\"\"Dispatch an event, draining self-callback escalation.\n\n");
    code.push_str("        Returns (effect_results, emitted_events). Emitted events this\n");
    code.push_str("        trait also handles (service-callbacks like EMBEDDED/INFERRED_RAW)\n");
    code.push_str("        are re-dispatched inline so a headless server completes the full\n");
    code.push_str("        rung chain in one call — mirroring the client-relay drain loop.\n");
    code.push_str("        \"\"\"\n");
    code.push_str("        effect_results: List[Dict] = []\n");
    code.push_str("        emitted_events: List[Dict] = []\n");
    code.push_str("        self._current_entity_id = None\n");
    code.push_str("        _queue = [(event, entity, payload)]\n");
    code.push_str("        _depth = 0\n");
    code.push_str("        while _queue and _depth < 50:\n");
    code.push_str("            _ev, _ent, _pay = _queue.pop(0)\n");
    code.push_str("            self._current_entity_id = _ent.get(\"id\") if isinstance(_ent, dict) else None\n");
    code.push_str("            _h = getattr(self, f'handle_{_ev}', None)\n");
    code.push_str("            if not _h:\n");
    code.push_str("                continue\n");
    code.push_str("            _eff, _emit = await _h(_ent, _pay)\n");
    code.push_str("            effect_results.extend(_eff)\n");
    code.push_str("            emitted_events.extend(_emit)\n");
    code.push_str("            for _e in _emit:\n");
    code.push_str("                _nev = _e.get(\"event\", \"\")\n");
    code.push_str("                if hasattr(self, f\"handle_{_nev}\"):\n");
    code.push_str("                    _queue.append((_nev, _ent, _e.get(\"payload\") or {}))\n");
    code.push_str("            _depth += 1\n");
    code.push_str("        return effect_results, emitted_events\n\n");

    // Generate event handlers
    if !trait_def.transitions.is_empty() {
        // Group transitions by event
        let mut transitions_by_event: std::collections::BTreeMap<&str, Vec<&OirTransition>> =
            std::collections::BTreeMap::new();

        for transition in &trait_def.transitions {
            transitions_by_event
                .entry(&transition.event)
                .or_default()
                .push(transition);
        }

        for (event, transitions) in transitions_by_event {
            code.push_str(&generate_event_handler(event, &transitions, trait_def));
            code.push_str("\n");
        }
    }

    code
}

/// Generate the LISTENS class attribute — cross-trait listen declarations.
///
/// Each entry: `{event, source_trait, source_any, triggers, payload_mapping}`.
/// `payload_mapping` is a dict of compiled Python exprs (or None) — the
/// startup wiring applies it to project the source payload before dispatch.
fn generate_listens_metadata(trait_def: &OirTrait) -> String {
    let mut code = String::new();
    code.push_str("    # Cross-trait listens — consumed by setup_event_listeners()\n");
    if trait_def.listeners.is_empty() {
        code.push_str("    LISTENS = []\n\n");
        return code;
    }
    code.push_str("    LISTENS = [\n");
    let ctx = CodegenContext {
        entity_var: Some("_source".to_string()),
        payload_var: Some("_source".to_string()),
        ..Default::default()
    };
    for listener in &trait_def.listeners {
        let event = &listener.event_pattern;
        let triggers = &listener.triggers;
        let source_trait = listener
            .source_trait
            .as_deref()
            .unwrap_or("");
        let source_any = if listener.source_any { "True" } else { "False" };
        // Compile payload mapping (if any) into lambdas evaluated at delivery
        // time against the source payload (mirrors JS applyListenPayloadMapping).
        let mapping_code = if let Some(ref mapping) = listener.payload_mapping {
            let entries: Vec<String> = mapping
                .iter()
                .map(|(k, v)| {
                    format!("\"{}\": (lambda _source: {})", k, compile_expr_to_py(v, &ctx))
                })
                .collect();
            format!("{{ {} }}", entries.join(", "))
        } else {
            "None".to_string()
        };
        code.push_str(&format!(
            "        {{\"event\": \"{}\", \"source_trait\": \"{}\", \"source_any\": {}, \"triggers\": \"{}\", \"payload_mapping\": {}}},\n",
            event, source_trait, source_any, triggers, mapping_code
        ));
    }
    code.push_str("    ]\n\n");
    code
}

/// Generate event handler method
fn generate_event_handler(
    event: &str,
    transitions: &[&OirTransition],
    trait_def: &OirTrait,
) -> String {
    let mut code = String::new();

    let state_enum = format!("{}State", trait_def.name);

    // Returns (effect_results, emitted_events) matching TS EventResponse contract
    code.push_str(&format!(
        "    async def handle_{}(self, entity: Any, payload: Dict[str, Any]) -> tuple:\n",
        event
    ));
    code.push_str(&format!("        \"\"\"Handle {} event. Returns (effect_results, emitted_events).\"\"\"\n", event));
    code.push_str("        effect_results: List[Dict] = []\n");
    code.push_str("        emitted_events: List[Dict] = []\n\n");

    // Generate if/elif chain for transitions with guards
    let mut first = true;
    for transition in transitions {
        let state_check = match &transition.from {
            OirTransitionFrom::Single(state) => {
                let from_state = state.to_uppercase().replace('-', "_");
                format!("self._state == {}.{}", state_enum, from_state)
            }
            OirTransitionFrom::Multiple(states) => {
                let state_checks: Vec<String> = states
                    .iter()
                    .map(|s| {
                        let from_state = s.to_uppercase().replace('-', "_");
                        format!("self._state == {}.{}", state_enum, from_state)
                    })
                    .collect();
                format!("({})", state_checks.join(" or "))
            }
            OirTransitionFrom::Any => "True".to_string(),
        };

        let has_guard = transition.guard.is_some();
        let guard_code = if let Some(ref guard) = transition.guard {
            let ctx = CodegenContext {
                entity_var: Some("entity".to_string()),
                payload_var: Some("payload".to_string()),
                ..Default::default()
            };
            compile_expr_to_py(guard, &ctx)
        } else {
            String::new()
        };

        if first {
            code.push_str(&format!("        if {}:\n", state_check));
            first = false;
        } else {
            code.push_str(&format!("        elif {}:\n", state_check));
        }

        // Guard enforcement — mirrors TS "Access denied: guard condition not met"
        if has_guard {
            code.push_str(&format!("            if not ({}):\n", guard_code));
            code.push_str("                return [{{\"effect\": \"guard\", \"success\": False, \"error\": \"Access denied: guard condition not met\"}}], []\n");
        }

        // Generate transition effects
        code.push_str(&generate_transition_effects(transition, trait_def));
    }

    // Default: unknown state for this event
    if !transitions.is_empty() {
        code.push_str("        else:\n");
        code.push_str(&format!(
            "            return [{{\"effect\": \"guard\", \"success\": False, \"error\": f\"Cannot process {} from state {{self._state.value}}\"}}], []\n",
            event
        ));
    }

    code.push_str("\n        return effect_results, emitted_events\n");
    code
}

/// Generate effects for a transition
fn generate_transition_effects(transition: &OirTransition, trait_def: &OirTrait) -> String {
    let mut code = String::new();

    let ctx = CodegenContext {
        entity_var: Some("entity".to_string()),
        payload_var: Some("payload".to_string()),
        ..Default::default()
    };

    // State transition
    let to_upper = transition.to.to_uppercase().replace('-', "_");
    let state_enum = format!("{}State", trait_def.name);
    code.push_str(&format!(
        "            self._state = {}.{}\n",
        state_enum, to_upper
    ));

    // Effects — a transition body is a sequence of statements that may nest
    // `(let …)`, `(do …)`, `(if …)` control flow. Mirrors TS
    // `emit_tick_effect_block` (codegen/effect/tick.rs): recurse into blocks,
    // emitting leaf effects at the current indent.
    for effect_expr in &transition.effects {
        code.push_str(&compile_effect_stmt(
            effect_expr,
            &ctx,
            trait_def,
            "            ",
        ));
    }

    code
}

/// Compile one transition-body statement (possibly nested) to Python lines.
/// Handles `(let …)` / `(do …)` / `(if …)` / `(when …)` control flow and
/// delegates leaf `OirExpr::Effect` to `compile_leaf_effect`. Mirrors the
/// statement-level recursion of TS `emit_tick_effect_block`.
fn compile_effect_stmt(
    expr: &OirExpr,
    ctx: &CodegenContext,
    trait_def: &OirTrait,
    indent: &str,
) -> String {
    match expr {
        OirExpr::Effect { effect } => compile_leaf_effect(effect, ctx, trait_def, indent),
        OirExpr::Call { function, args } if function == "let" && args.len() == 2 => {
            let mut out = String::new();
            let mut local_ctx = ctx.clone();
            // args[0] is an Array of [name, value] pairs (confirmed in TS expr.rs)
            if let Some(OirExpr::Array { items }) = args.get(0) {
                for pair in items {
                    if let OirExpr::Array { items: kv } = pair {
                        if kv.len() == 2 {
                            if let OirExpr::String { value: name } = &kv[0] {
                                let value_code = compile_expr_to_py(&kv[1], &local_ctx);
                                out.push_str(&format!("{}{} = {}\n", indent, name, value_code));
                                local_ctx = local_ctx.with_local(name, name);
                            }
                        }
                    }
                }
            }
            out.push_str(&compile_effect_stmt(&args[1], &local_ctx, trait_def, indent));
            out
        }
        OirExpr::Call { function, args } if function == "do" => {
            let mut out = String::new();
            for arg in args {
                out.push_str(&compile_effect_stmt(arg, ctx, trait_def, indent));
            }
            out
        }
        OirExpr::Call { function, args }
            if (function == "if" || function == "when") && args.len() >= 2 =>
        {
            let cond = compile_expr_to_py(&args[0], ctx);
            let inner = format!("{}    ", indent);
            let mut out = format!("{}if {}:\n", indent, cond);
            let then_code = compile_effect_stmt(&args[1], ctx, trait_def, &inner);
            if then_code.trim().is_empty() {
                out.push_str(&format!("{}pass\n", inner));
            } else {
                out.push_str(&then_code);
            }
            if function == "if" && args.len() >= 3 {
                out.push_str(&format!("{}else:\n", indent));
                let else_code = compile_effect_stmt(&args[2], ctx, trait_def, &inner);
                if else_code.trim().is_empty() {
                    out.push_str(&format!("{}pass\n", inner));
                } else {
                    out.push_str(&else_code);
                }
            }
            out
        }
        // Enriched `if` — the compiler lowers `(if c t e)` to
        // `OirExpr::Conditional`. In statement position (a transition body)
        // it is control flow whose branches hold statements (`do`/`set`/
        // `emit`), so emit a real if/else block and recurse via
        // `compile_effect_stmt`. (Value-position Conditionals — inside a
        // `set` or `let` binding — are still compiled to ternaries by
        // `compile_expr_to_py`, because their branches are reached via the
        // expression compiler, not this function.)
        OirExpr::Conditional {
            condition,
            then_branch,
            else_branch,
        } => {
            let cond = compile_expr_to_py(condition, ctx);
            let inner = format!("{}    ", indent);
            let mut out = format!("{}if {}:\n", indent, cond);
            let then_code = compile_effect_stmt(then_branch, ctx, trait_def, &inner);
            if then_code.trim().is_empty() {
                out.push_str(&format!("{}pass\n", inner));
            } else {
                out.push_str(&then_code);
            }
            out.push_str(&format!("{}else:\n", indent));
            let else_code = compile_effect_stmt(else_branch, ctx, trait_def, &inner);
            if else_code.trim().is_empty() {
                out.push_str(&format!("{}pass\n", inner));
            } else {
                out.push_str(&else_code);
            }
            out
        }
        // Other expression in statement position (pure side-effect call).
        // `compile_expr_to_py` emits an UNSUPPORTED marker for unknown operators;
        // the backend pre-write scan fails compilation on any such marker, so
        // drift is caught rather than silently dropped.
        other => {
            let compiled = compile_expr_to_py(other, ctx);
            if !compiled.is_empty() && !compiled.starts_with('#') {
                format!("{}{}\n", indent, compiled)
            } else {
                String::new()
            }
        }
    }
}

/// Compile a leaf `OirEffect` to Python line(s) at `indent`. Extracted from
/// the old flat loop so nested control flow (`let`/`do`/`if`) can reach it at
/// any indentation depth.
#[allow(clippy::too_many_lines)]
fn compile_leaf_effect(
    effect: &OirEffect,
    ctx: &CodegenContext,
    trait_def: &OirTrait,
    indent: &str,
) -> String {
    let mut code = String::new();
    match effect {
        OirEffect::Emit { event, payload } => {
            let payload_code = if let Some(p) = payload {
                compile_expr_to_py(p, ctx)
            } else {
                "{}".to_string()
            };
            let inner = format!("{}    ", indent);
            code.push_str(&format!(
                "{}if self._event_bus:\n{}await self._event_bus.emit(\"{}\", {})\n",
                indent, inner, event, payload_code
            ));
            code.push_str(&format!(
                "{}emitted_events.append({{\"event\": \"{}\", \"payload\": {}}})\n",
                indent, event, payload_code
            ));
            code.push_str(&format!(
                "{}effect_results.append({{\"effect\": \"emit\", \"success\": True, \"data\": {{\"event\": \"{}\", \"payload\": {}}}}})\n",
                indent, event, payload_code
            ));
        }
        OirEffect::Persist { operation, entity_type, data, .. } => {
            let data_code = compile_expr_to_py(data, ctx);
            let resolved = if entity_type == "@entity" {
                trait_def.linked_entity.as_deref().unwrap_or("Entity")
            } else {
                entity_type.as_str()
            };
            let op_str = match operation {
                OirPersistOp::Create => "create",
                OirPersistOp::Read => "read",
                OirPersistOp::Update => "update",
                OirPersistOp::Delete => "delete",
                OirPersistOp::List => "list",
                OirPersistOp::Query => "query",
            };
            code.push_str(&format!("{}# Persist {} ({})\n", indent, resolved, op_str));
            let inner = format!("{}    ", indent);
            match operation {
                OirPersistOp::Create => {
                    code.push_str(&format!("{}_persist_data = {}\n", indent, data_code));
                    code.push_str(&format!("{}_persist_id = _persist_data.get(\"id\") if isinstance(_persist_data, dict) else None\n", indent));
                    code.push_str(&format!(
                        "{}await self._repository.create(\"{}\", _persist_data)\n",
                        indent, to_snake_case(resolved)
                    ));
                    code.push_str(&format!(
                        "{}effect_results.append({{\"effect\": \"persist\", \"action\": \"create\", \"entityType\": \"{}\", \"success\": True, \"data\": _persist_data}})\n",
                        indent, resolved
                    ));
                }
                OirPersistOp::Update => {
                    code.push_str(&format!("{}_update_data = {}\n", indent, data_code));
                    code.push_str(&format!("{}_update_id = _update_data.get(\"id\") or (entity.get(\"id\") if isinstance(entity, dict) else None)\n", indent));
                    code.push_str(&format!(
                        "{}if _update_id:\n{}await self._repository.update(\"{}\", _update_id, _update_data)\n",
                        indent, inner, to_snake_case(resolved)
                    ));
                    code.push_str(&format!(
                        "{}effect_results.append({{\"effect\": \"persist\", \"action\": \"update\", \"entityType\": \"{}\", \"success\": bool(_update_id), \"data\": _update_data}})\n",
                        indent, resolved
                    ));
                }
                OirPersistOp::Delete => {
                    code.push_str(&format!("{}_delete_id = {}\n", indent, data_code));
                    code.push_str(&format!("{}_delete_id_str = _delete_id if isinstance(_delete_id, str) else (_delete_id.get(\"id\") if isinstance(_delete_id, dict) else None)\n", indent));
                    code.push_str(&format!(
                        "{}if _delete_id_str:\n{}await self._repository.delete(\"{}\", _delete_id_str)\n",
                        indent, inner, to_snake_case(resolved)
                    ));
                    code.push_str(&format!(
                        "{}effect_results.append({{\"effect\": \"persist\", \"action\": \"delete\", \"entityType\": \"{}\", \"success\": bool(_delete_id_str)}})\n",
                        indent, resolved
                    ));
                }
                _ => {
                    code.push_str(&format!(
                        "{}_fetched = await self._repository.list(\"{}\")\n",
                        indent, to_snake_case(resolved)
                    ));
                    code.push_str(&format!(
                        "{}effect_results.append({{\"effect\": \"persist\", \"action\": \"{}\", \"entityType\": \"{}\", \"success\": True, \"data\": _fetched}})\n",
                        indent, op_str, resolved
                    ));
                }
            }
        }
        OirEffect::CallService {
            service,
            method,
            args,
            emit,
            ..
        } => {
            let args_code = compile_expr_to_py(args, ctx);
            let inner = format!("{}    ", indent);
            let inner2 = format!("{}    ", inner);
            code.push_str(&format!("{}# Call service {}.{}\n", indent, service, method));
            code.push_str(&format!("{}try:\n", indent));
            code.push_str(&format!(
                "{}_svc_result = await self._call_service(\"{}\", \"{}\", {})\n",
                inner, service, method, args_code
            ));
            if let Some(ev) = emit.as_ref().and_then(|c| c.success.as_ref()) {
                code.push_str(&format!(
                    "{}_emit_payload = _svc_result if isinstance(_svc_result, dict) else {{\"result\": _svc_result}}\n",
                    inner
                ));
                code.push_str(&format!(
                    "{}if self._event_bus:\n{}await self._event_bus.emit(\"{}\", _emit_payload)\n",
                    inner, inner2, ev
                ));
                code.push_str(&format!(
                    "{}emitted_events.append({{\"event\": \"{}\", \"payload\": _emit_payload}})\n",
                    inner, ev
                ));
            }
            code.push_str(&format!(
                "{}effect_results.append({{\"effect\": \"call-service\", \"action\": \"{}\", \"success\": True, \"data\": _svc_result}})\n",
                inner, method
            ));
            code.push_str(&format!("{}except Exception as _svc_err:\n", indent));
            if let Some(ev) = emit.as_ref().and_then(|c| c.failure.as_ref()) {
                code.push_str(&format!(
                    "{}if self._event_bus:\n{}await self._event_bus.emit(\"{}\", {{\"error\": str(_svc_err)}})\n",
                    inner, inner2, ev
                ));
                code.push_str(&format!(
                    "{}emitted_events.append({{\"event\": \"{}\", \"payload\": {{\"error\": str(_svc_err)}}}})\n",
                    inner, ev
                ));
            }
            code.push_str(&format!(
                "{}effect_results.append({{\"effect\": \"call-service\", \"action\": \"{}\", \"success\": False, \"error\": str(_svc_err)}})\n",
                inner, method
            ));
        }
        OirEffect::PersistBatch { .. } => {
            code.push_str(&format!(
                "{}# {}\n",
                indent,
                orbital_core::unsupported_operator_marker("persist batch")
            ));
        }
        OirEffect::CancelCall { .. } => {
            code.push_str(&format!(
                "{}# {}\n",
                indent,
                orbital_core::unsupported_operator_marker("cancel-call")
            ));
        }
        OirEffect::Set { target, value, .. } => {
            let target_code = compile_binding_to_py(target, ctx);
            let value_code = compile_expr_to_py(value, ctx);
            if target.path.last().map(|s| s.as_str()) == Some("architecture") {
                code.push_str(&format!("{}self._set_architecture(entity[\"id\"], {})\n", indent, value_code));
            } else {
                code.push_str(&format!("{}{} = {}\n", indent, target_code, value_code));
            }
        }
        OirEffect::Custom { name, args, .. } if name.starts_with("agent/") => {
            let method = &name["agent/".len()..];
            let mut sorted_args: Vec<(&String, &OirExpr)> = args.iter().collect();
            sorted_args.sort_by(|a, b| a.0.cmp(b.0));
            let arg_exprs: Vec<String> = sorted_args
                .iter()
                .map(|(_, v)| compile_expr_to_py(v, ctx))
                .collect();
            code.push_str(&format!("{}# agent/{}\n", indent, method));
            match method {
                "memorize" => {
                    let content = arg_exprs.first().map_or("\"\"".to_string(), |s| s.clone());
                    let category = arg_exprs.get(1).map_or("\"preference\"".to_string(), |s| s.clone());
                    let scope = arg_exprs.get(2).map_or("\"global\"".to_string(), |s| s.clone());
                    code.push_str(&format!("{}import uuid\n", indent));
                    code.push_str(&format!("{}_mem_id = str(uuid.uuid4())\n", indent));
                    code.push_str(&format!(
                        "{}await self._repository.create(\"memories\", {{\"id\": _mem_id, \"content\": {}, \"category\": {}, \"scope\": {}, \"strength\": 0.5, \"pinned\": False}})\n",
                        indent, content, category, scope
                    ));
                    code.push_str(&format!("{}effect_results.append({{\"effect\": \"agent\", \"action\": \"memorize\", \"success\": True, \"data\": {{\"id\": _mem_id}}}})\n", indent));
                }
                "recall" => {
                    let query = arg_exprs.first().map_or("\"\"".to_string(), |s| s.clone());
                    let limit = arg_exprs.get(1).map_or("10".to_string(), |s| s.clone());
                    code.push_str(&format!("{}_all_mems = await self._repository.list(\"memories\")\n", indent));
                    code.push_str(&format!(
                        "{}_recalled = sorted([m for m in _all_mems if {} in str(m.get(\"content\", \"\"))], key=lambda m: -m.get(\"strength\", 0))[:{} or 10]\n",
                        indent, query, limit
                    ));
                    code.push_str(&format!("{}effect_results.append({{\"effect\": \"agent\", \"action\": \"recall\", \"success\": True, \"data\": _recalled}})\n", indent));
                }
                "forget" => {
                    let id = arg_exprs.first().map_or("\"\"".to_string(), |s| s.clone());
                    code.push_str(&format!("{}await self._repository.delete(\"memories\", {})\n", indent, id));
                    code.push_str(&format!("{}effect_results.append({{\"effect\": \"agent\", \"action\": \"forget\", \"success\": True, \"data\": {{\"id\": {}}}}})\n", indent, id));
                }
                "generate" => {
                    let prompt = arg_exprs.first().map_or("\"\"".to_string(), |s| s.clone());
                    code.push_str(&format!("{}_gen_result = await self._llm_generate({})\n", indent, prompt));
                    code.push_str(&format!("{}effect_results.append({{\"effect\": \"agent\", \"action\": \"generate\", \"success\": True, \"data\": {{\"text\": _gen_result}}}})\n", indent));
                }
                "invoke" => {
                    let tool_name = arg_exprs.first().map_or("\"\"".to_string(), |s| s.clone());
                    let tool_args = arg_exprs.get(1).map_or("{}".to_string(), |s| s.clone());
                    code.push_str(&format!("{}_tool_result = await self._invoke_tool({}, {})\n", indent, tool_name, tool_args));
                    code.push_str(&format!("{}effect_results.append({{\"effect\": \"agent\", \"action\": \"invoke\", \"success\": True, \"data\": _tool_result}})\n", indent));
                }
                _ => {
                    code.push_str(&format!("{}# agent/{} (no-op)\n", indent, method));
                }
            }
        }
        OirEffect::Custom { name, args, emit, .. } if is_substrate_operator(name) => {
            code.push_str(&compile_substrate_service_call(name, args, emit.as_ref(), ctx, indent));
        }
        OirEffect::Log { level, message } => {
            let msg = compile_expr_to_py(message, ctx);
            let level_str = format!("{:?}", level).to_lowercase();
            code.push_str(&format!("{}print(\"[{}]\", {})\n", indent, level_str, msg));
        }
        OirEffect::RenderUi { .. }
        | OirEffect::Navigate { .. }
        | OirEffect::Spawn { .. }
        | OirEffect::Despawn { .. }
        | OirEffect::SendServer { .. }
        | OirEffect::BrowserOpenFilePicker { .. }
        | OirEffect::BrowserClipboardRead { .. }
        | OirEffect::BrowserClipboardWrite { .. }
        | OirEffect::BrowserGeolocationCurrent { .. }
        | OirEffect::BrowserPushSubscribe { .. } => {
            let compiled = compile_expr_to_py(&OirExpr::Effect { effect: Box::new(effect.clone()) }, ctx);
            code.push_str(&format!(
                "{}effect_results.append({{\"effect\": \"client\", \"success\": True, \"data\": {}}})\n",
                indent, compiled
            ));
        }
        _ => {
            let compiled = compile_expr_to_py(&OirExpr::Effect { effect: Box::new(effect.clone()) }, ctx);
            if compiled.contains(" = ") && !compiled.starts_with('{') {
                code.push_str(&format!("{}{}\n", indent, compiled));
            } else if compiled.starts_with("ml_forward(")
                || compiled.starts_with("ml_train(")
                || compiled.starts_with("ml_evaluate(")
            {
                code.push_str(&format!("{}_ml_result = {}\n", indent, compiled));
                let inner = format!("{}    ", indent);
                let inner2 = format!("{}        ", indent);
                code.push_str(&format!("{}if isinstance(_ml_result, dict):\n", indent));
                code.push_str(&format!("{}_on_complete = _ml_result.get('_on_complete')\n", inner));
                code.push_str(&format!("{}if _on_complete and self._event_bus:\n", inner));
                code.push_str(&format!("{}import asyncio\n", inner2));
                code.push_str(&format!("{}asyncio.ensure_future(self._event_bus.emit(_on_complete, _ml_result))\n", inner2));
                code.push_str(&format!("{}effect_results.append({{\"effect\": \"ml\", \"success\": True, \"data\": _ml_result}})\n", indent));
            } else if !compiled.is_empty() && !compiled.starts_with('#') {
                code.push_str(&format!(
                    "{}effect_results.append({{\"effect\": \"custom\", \"success\": True, \"data\": {}}})\n",
                    indent, compiled
                ));
            }
        }
    }
    code
}

/// Compile a substrate service-call effect (`llm/*`, `workspace/*`, …) with
/// optional success/failure emit routing. Mirrors the TS substrate-op emit
/// envelope (`client.rs::device_emit_lines`): success → `{ result }`, failure
/// → `{ error }`. The service is invoked via `self._call_service` (the
/// Python shell's injected service client).
fn compile_substrate_service_call(
    name: &str,
    args: &orbital_core::ir::OirFields,
    emit: Option<&OirEmitConfig>,
    ctx: &CodegenContext,
    indent: &str,
) -> String {
    let mut sorted: Vec<(&String, &OirExpr)> = args.iter().collect();
    sorted.sort_by(|a, b| a.0.cmp(b.0));
    let arg_values: Vec<String> = sorted.iter().map(|(_, v)| compile_expr_to_py(v, ctx)).collect();
    // `llm/embed` → service "llm", method "embed"; generic `svc/method` split.
    let (service, method) = name
        .split_once('/')
        .map(|(s, m)| (s.to_string(), m.to_string()))
        .unwrap_or((name.to_string(), "invoke".to_string()));
    let inner = format!("{}    ", indent);
    let mut code = String::new();
    code.push_str(&format!("{}try:\n", indent));
    code.push_str(&format!(
        "{}_svc_result = await self._call_service(\"{}\", \"{}\", [{}])\n",
        inner, service, method, arg_values.join(", ")
    ));
    if let Some(ev) = emit.and_then(|c| c.success.as_ref()) {
        code.push_str(&format!(
            "{}if self._event_bus:\n{}await self._event_bus.emit(\"{}\", {{\"result\": _svc_result}})\n",
            inner, format!("{}    ", inner), ev
        ));
        code.push_str(&format!(
            "{}emitted_events.append({{\"event\": \"{}\", \"payload\": {{\"result\": _svc_result}}}})\n",
            inner, ev
        ));
    }
    code.push_str(&format!(
        "{}effect_results.append({{\"effect\": \"{}\", \"action\": \"{}\", \"success\": True, \"data\": _svc_result}})\n",
        inner, service, method
    ));
    code.push_str(&format!("{}except Exception as _svc_err:\n", indent));
    if let Some(ev) = emit.and_then(|c| c.failure.as_ref()) {
        code.push_str(&format!(
            "{}if self._event_bus:\n{}await self._event_bus.emit(\"{}\", {{\"error\": str(_svc_err)}})\n",
            inner, format!("{}    ", inner), ev
        ));
        code.push_str(&format!(
            "{}emitted_events.append({{\"event\": \"{}\", \"payload\": {{\"error\": str(_svc_err)}}}})\n",
            inner, ev
        ));
    }
    code.push_str(&format!(
        "{}effect_results.append({{\"effect\": \"{}\", \"action\": \"{}\", \"success\": False, \"error\": str(_svc_err)}})\n",
        inner, service, method
    ));
    code
}

